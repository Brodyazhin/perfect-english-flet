def count_words(item):
    if "words" in item:
        return len(item["words"])
    if "subsections" in item:
        return sum(count_words(s) for s in item["subsections"].values())
    return 0


def collect_words(item, out=None, kind=None):
    """Собирает слова, обогащая каждое полем 'type' (из kind подраздела)."""
    if out is None:
        out = []
    k = item.get("kind") or kind or "word"
    if "words" in item:
        for w in item["words"]:
            ww = dict(w)
            ww.setdefault("type", k)
            out.append(ww)
    if "subsections" in item:
        for s in item["subsections"].values():
            collect_words(s, out, k)
    return out


